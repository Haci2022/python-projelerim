import math 

#numpay,pandas vb.. gibi terimler python dilinde birer kütüphanedeir.


#floor()= sayıyı kendisine en yakın küçük tam sayıyıa çevirir

print(math.floor(4.6))


#ceil()= sayıyı kendisine en yakın büyük tam sayıya çevirir.

print(math.ceil(5.3))


#round()= sayıyı en yakın olduğu sayıya yuvarlar

print(round(12.3))

#sqrt()= matematikteki karekök iişlemine karşılık gelen komuttur

print(math.sqrt(16))


#log()= matematikteki logaritma işlemine karşı gelen bir komuttur.

print(math.log(8.2))